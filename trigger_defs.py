MAX_BLOCK = 64


def action_meta():
    """给前端用的动作表（按编号排序）"""
    out = []
    for aid in sorted(ACTIONS):
        d = ACTIONS[aid]
        out.append({
            'id': aid, 'name': d['name'], 'desc': d['desc'], 'pt': d['pt'],
            'wpt': bool(d['wpt']),
            'params': [{'label': lb, 'kind': kd} for lb, kd in d['params']],
        })
    return out


def _err(msg):
    return {'ok': False, 'err': msg, 'blocks': []}


def parse_actions(value):
    """把一行 [Actions] 值拆成结果块。字段数不符就判失败，前端退回纯文本编辑。"""
    s = (value or '').strip()
    if not s:
        return _err('空值')
    parts = [x.strip() for x in s.split(',')]
    try:
        n = int(parts[0])
    except Exception:
        return _err('第一个字段不是结果数量')
    if n < 0 or n > MAX_BLOCK:
        return _err('结果数量异常：%d' % n)
    body = parts[1:]
    if len(body) != n * 8:
        return _err('字段数 %d 与结果数量 %d 不符（应为 %d 个字段）'
                    % (len(body), n, n * 8))
    blocks = []
    for i in range(n):
        f = body[i * 8:(i + 1) * 8]
        try:
            aid = int(f[0])
        except Exception:
            return _err('第 %d 个结果的类型不是数字：%s' % (i + 1, f[0]))
        blocks.append({'id': aid, 'pt': f[1], 'ps': f[2:7], 'wpt': f[7]})
    return {'ok': True, 'err': '', 'blocks': blocks}


def compose_actions(blocks):
    """结果块 -> 一行 [Actions] 值。路径点统一大写，参数不足补 0。"""
    blocks = list(blocks or [])
    if not blocks:
        return '0'
    out = [str(len(blocks))]
    for b in blocks:
        try:
            aid = int(b.get('id'))
        except Exception:
            raise ValueError('结果类型必须是数字')
        d = ACTIONS.get(aid, {})
        pt = b.get('pt')
        if pt in (None, ''):
            pt = d.get('pt', 0)
        ps = [str(x if x is not None else '') for x in (b.get('ps') or [])][:5]
        while len(ps) < 5:
            ps.append('0')
        ps = [('0' if x == '' else x) for x in ps]
        wpt = (str(b.get('wpt') or 'A')).strip().upper().replace(' ', '') or 'A'
        out.append(str(aid))
        out.append(str(pt).strip() or '0')
        out.extend(ps)
        out.append(wpt)
    return ','.join(out)


def default_block(aid, ctx, self_id=''):
    """选了一个动作类型后，后台给出的默认参数串（前端直接照着填）。"""
    d = ACTIONS.get(int(aid), {})
    ps = []
    for lb, kind in d.get('params', []):
        if kind == K_HOUSE:
            # 动作 14「更改所属方」在真实地图里用的都是 4475~4482（玩家 A~H），默认就给玩家 A
            ps.append('4475' if int(aid) == 14 else ctx['house'])
        elif kind == K_TEAM:
            ps.append(ctx['team'])
        elif kind == K_TRIG:
            ps.append(self_id or ctx['trigger'])
        elif kind == K_WP:
            ps.append(ctx['wp'])
        elif kind == K_ONOFF:
            ps.append('0')
        elif kind == K_TEXT:
            ps.append('')
        else:
            ps.append('0')
    while len(ps) < 5:
        ps.append('0')
    return {'id': int(aid), 'pt': d.get('pt', 0), 'ps': ps[:5], 'wpt': ctx['wpt']}


def base26(n):
    """0->A 1->B 25->Z 26->AA（与 FA2 的路径点字段一致）"""
    n = int(n)
    s = ''
    while True:
        s = chr(ord('A') + n % 26) + s
        n = n // 26 - 1
        if n < 0:
            break
    return s


def unbase26(s):
    s = (s or '').strip().upper()
    if not s or not all('A' <= c <= 'Z' for c in s):
        return None
    n = 0
    for c in s:
        n = n * 26 + (ord(c) - ord('A') + 1)
    return n - 1
